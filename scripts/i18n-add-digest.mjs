for (const [code, dict] of Object.entries(DIGEST)) {
  const path = `messages/${code}.json`;
  const obj = JSON.parse(readFileSync(path, "utf8"));
  if (obj.digest) { console.log(`${code}: digest already present — skipping`); continue; }
  obj.digest = dict;
  const out = (JSON.stringify(obj, null, 2) + "\n").replace(/\n/g, "\r\n");
  writeFileSync(path, out, "utf8");
  console.log(`${code}: added digest (${Object.keys(dict).length} keys)`);
}
